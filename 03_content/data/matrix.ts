/** Średnia grupy kryteriów dla mechanizmu. */
export function groupMean(mechId: string, group: Criterion['group']): number {
  const list = criteria.filter((c) => c.group === group).map((c) => scores[mechId][c.id].v);
  return list.reduce((a, b) => a + b, 0) / list.length;
}

/** Wynik ważony 1–5 dla profilu. */
export function weighted(mechId: string, profile: Profile): number {
  return (Object.keys(profile.weights) as Criterion['group'][]).reduce((sum, g) => sum + profile.weights[g] * groupMean(mechId, g), 0);
}
